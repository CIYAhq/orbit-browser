/**
 * The emoji with a skin-tone modifier applied (when it accepts one). The
 * modifier goes right after the first code point, replacing a U+FE0F
 * variation selector there; the rest of a ZWJ sequence is kept.
 */
export function withTone(entry: EmojiEntry, modifier: string): string {
  if (!modifier || !entry.t) return entry.e
  const points = [...entry.e]
  const first = points[0]
  if (!first) return entry.e
  const rest = points.slice(1)
  if (rest[0] === '️') rest.shift()
  return first + modifier + rest.join('')
}


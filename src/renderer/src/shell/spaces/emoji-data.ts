/**
 * Emoji for Space icons (SP-05): a small, curated set written for Orbit,
 * grouped by category. Names are short and lowercase; `k` adds search words.
 */

export interface EmojiEntry {
  /** The emoji itself. */
  e: string
  /** Short lowercase name (tooltip, search). */
  n: string
  /** Extra search keywords, space-separated. */
  k?: string
  /** Accepts a skin-tone modifier. */
  t?: true
}

export interface EmojiCategory {
  id: string
  label: string
  icon: string
  items: EmojiEntry[]
}

export interface SkinTone {
  id: string
  label: string
  /** Fitzpatrick modifier ('' for the default yellow). */
  modifier: string
  /** Colour of the tone's swatch in the picker. */
  swatch: string
}

